"""Generate a data-driven options.lua (Mod Manager options screen).

gen_options(path, title=(en, ru), subtitle=(en, ru), rows=[...])

Row kinds:
  {"kind": "slider", "key": "radius", "label": ("Radius", "Радиус"), "min": 3, "max": 20,
   "default": 8, "fmt": ("%.1f m", "%.1f м"), "int": False, "step": 0.1}
  {"kind": "choice", "key": "impact", "label": (...), "default": False,
   "choices": [(False, "After stopping", "После остановки"), (True, "On impact", "От удара")]}
Values are stored as savegame.mod.<key> (SetFloat / SetInt / SetBool / SetString by type).
"""
from __future__ import annotations

import math
import os

TEMPLATE = r'''-- Options screen (generated by _shared/tdlib/options_gen.py).
-- Values are stored in savegame.mod.* and read by main.lua.

local PANEL_W = __PANEL_W__
local LABEL_W = __LABEL_W__       -- the label column: the longest label in the game's font (at least 330 px)
local ROW_H = 44
local SLIDER_W = 260

local function ru() return GetInt("options.language") == 7 end
local function tr(pair) if ru() then return pair[2] end return pair[1] end

local TITLE = __TITLE__
local SUBTITLE = __SUBTITLE__
local ROWS = __ROWS__

local function key(r) return "savegame.mod." .. r.key end

local function getValue(r)
	local k = key(r)
	if not HasKey(k) then return r.default end
	local t = type(r.default)
	if t == "boolean" then return GetBool(k) end
	if t == "string" then return GetString(k) end
	if r.int then return GetInt(k) end
	return GetFloat(k)
end

local function setValue(r, v)
	local k = key(r)
	local t = type(r.default)
	if t == "boolean" then SetBool(k, v)
	elseif t == "string" then SetString(k, v)
	elseif r.int then SetInt(k, v)
	else SetFloat(k, v) end
end

local function resetDefaults()
	for i = 1, #ROWS do setValue(ROWS[i], ROWS[i].default) end
end

local function sliderRow(r)
	local value = getValue(r)
	UiPush()
		UiAlign("left middle")
		UiFont("regular.ttf", 24)
		UiColor(1, 1, 1, 0.9)
		UiText(tr(r.label))
		UiTranslate(LABEL_W, 0)
		UiColor(1, 1, 1, 0.25)
		UiRect(SLIDER_W, 4)
		local t = (value - r.min) / (r.max - r.min)
		if t < 0 then t = 0 elseif t > 1 then t = 1 end
		UiColor(__ACCENT__, 1)
		UiRect(SLIDER_W * t, 4)
		UiColor(1, 1, 1, 1)
		UiTranslate(-10, 0)
		local pos = UiSlider("MOD/ui/dot.png", "x", SLIDER_W * t, 0, SLIDER_W)
		local nv = r.min + (pos / SLIDER_W) * (r.max - r.min)
		local step = r.step or 0.1
		nv = math.floor(nv / step + 0.5) * step
		if r.int then nv = math.floor(nv + 0.5) end
		if math.abs(nv - value) > 1e-6 then setValue(r, nv) end
		UiTranslate(SLIDER_W + 40, 0)
		UiFont("bold.ttf", 24)
		UiText(string.format(tr(r.fmt), getValue(r)))
	UiPop()
end

local function choiceRow(r)
	local current = getValue(r)
	local idx = 1
	for i = 1, #r.choices do if r.choices[i][1] == current then idx = i end end
	UiPush()
		UiAlign("left middle")
		UiFont("regular.ttf", 24)
		UiColor(1, 1, 1, 0.9)
		UiText(tr(r.label))
		UiTranslate(LABEL_W, 0)
		UiFont("bold.ttf", 24)
		UiColor(1, 1, 1, 1)
		UiButtonImageBox("ui/common/box-outline-6.png", 6, 6, 1, 1, 1, 0.6)
		UiButtonHoverColor(__ACCENT__, 1)
		local c = r.choices[idx]
		local label = c[2]
		if ru() then label = c[3] end
		if UiTextButton(label, 340, 36) then
			setValue(r, r.choices[(idx % #r.choices) + 1][1])
		end
	UiPop()
end

function draw()
	local h = 190 + #ROWS * ROW_H
	UiPush()
		UiColor(0, 0, 0, 0.55)
		UiRect(UiWidth(), UiHeight())
	UiPop()
	UiPush()
		UiTranslate(UiCenter(), UiMiddle())
		UiAlign("center middle")
		UiColor(0.06, 0.06, 0.08, 0.93)
		UiRoundedRect(PANEL_W, h, 14)
		UiColor(__ACCENT__, 0.8)
		UiRoundedRectOutline(PANEL_W, h, 14, 2)
		UiTranslate(0, -h / 2 + 46)
		UiFont("bold.ttf", 40)
		UiColor(1, 1, 1, 1)
		UiText(tr(TITLE))
		UiTranslate(0, 34)
		UiFont("regular.ttf", 20)
		UiColor(__ACCENT__, 0.8)
		UiText(tr(SUBTITLE))
		UiTranslate(-PANEL_W / 2 + 40, 50)
		for i = 1, #ROWS do
			local r = ROWS[i]
			if r.kind == "slider" then sliderRow(r) else choiceRow(r) end
			UiTranslate(0, ROW_H)
		end
		UiTranslate(PANEL_W / 2 - 40, 26)
		UiAlign("center middle")
		UiFont("regular.ttf", 22)
		UiColor(1, 1, 1, 1)
		UiButtonImageBox("ui/common/box-outline-6.png", 6, 6, 1, 1, 1, 0.8)
		UiPush()
			UiTranslate(-130, 0)
			if UiTextButton(tr({ "Reset to defaults", "Сбросить" }), 230, 44) then resetDefaults() end
		UiPop()
		UiPush()
			UiTranslate(130, 0)
			if UiTextButton(tr({ "Close", "Закрыть" }), 230, 44) then Menu() end
		UiPop()
	UiPop()
end
'''


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lua_val(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return lua_str(v)
    raise TypeError(v)


def pair(p) -> str:
    return "{ " + lua_str(p[0]) + ", " + lua_str(p[1]) + " }"


FONT = os.path.join(os.environ.get("TEARDOWN_DIR", r"C:\Program Files (x86)\Steam\steamapps\common\Teardown"),
                    "data", "ui", "font", "regular.ttf")
MIN_LABEL_W, MIN_PANEL_W, GAP = 330, 820, 20


def label_width(text: str) -> float:
    """Width in px of a settings label in the game's own font (regular.ttf 24, as the options screen draws it).
    Review 17.10: the catapult's "Урон от падения для запущенного игрока" is 471 px and ran into its button
    in the old fixed 330 px column."""
    from PIL import ImageFont
    return ImageFont.truetype(FONT, 24).getlength(text)


def layout(rows) -> tuple[int, int]:
    """(label column, panel width): the column fits the longest label (en and ru) plus a gap, the panel fits
    the column, the 340 px button (or the 260 px slider with its value) and the margins."""
    longest = max((label_width(t) for r in rows for t in r["label"]), default=0)
    col = max(MIN_LABEL_W, int(math.ceil(longest)) + GAP)
    return col, max(MIN_PANEL_W, col + 450)


def check_options(path: str) -> list[str]:
    """The law for a generated options.lua: every label is narrower than its column (by the game's font)."""
    import re
    src = open(path, encoding="utf-8").read()
    m = re.search(r"^local LABEL_W = (\d+)", src, re.M)
    if not m:
        return []
    col = int(m.group(1))
    out = []
    for en, ru in re.findall(r'label = \{ "((?:[^"\\]|\\.)*)", "((?:[^"\\]|\\.)*)" \}', src):
        for t in (en, ru):
            w = label_width(t)
            if w + GAP > col:
                out.append(f"{os.path.basename(os.path.dirname(os.path.dirname(path)))}: label \"{t}\" is {w:.0f} px, column {col} px")
    return out


def gen_options(path: str, title, subtitle, rows, accent=(0.75, 0.45, 1.0)) -> None:
    out = []
    for r in rows:
        f = [f'kind = {lua_str(r["kind"])}', f'key = {lua_str(r["key"])}', f'label = {pair(r["label"])}',
             f'default = {lua_val(r["default"])}']
        if r["kind"] == "slider":
            f += [f'min = {lua_val(r["min"])}', f'max = {lua_val(r["max"])}', f'fmt = {pair(r["fmt"])}',
                  f'int = {lua_val(bool(r.get("int", False)))}', f'step = {lua_val(r.get("step", 1 if r.get("int") else 0.1))}']
        else:
            ch = ", ".join("{ " + lua_val(c[0]) + ", " + lua_str(c[1]) + ", " + lua_str(c[2]) + " }" for c in r["choices"])
            f.append("choices = { " + ch + " }")
            if r.get("int"):
                f.append("int = true")
        out.append("\t{ " + ", ".join(f) + " },")
    src = TEMPLATE.replace("__TITLE__", pair(title)).replace("__SUBTITLE__", pair(subtitle))
    src = src.replace("__ROWS__", "{\n" + "\n".join(out) + "\n}")
    src = src.replace("__ACCENT__", ", ".join(f"{c:g}" for c in accent))
    col, panel = layout(rows)
    src = src.replace("__LABEL_W__", str(col)).replace("__PANEL_W__", str(panel))
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)
